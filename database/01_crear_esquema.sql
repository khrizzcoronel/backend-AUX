-- Ejecutar en pgAdmin conectado a "sga-auxiliar01".
-- Esquema derivado de las ocho entidades JPA de backend-AUX.
-- Los identificadores mixtos como id_Periodo se normalizan a minusculas
-- al no estar entre comillas en PostgreSQL/Hibernate.
BEGIN;

CREATE TABLE public.usuarios (
    id_usuario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cedula varchar(255) NOT NULL UNIQUE,
    nombres varchar(255) NOT NULL,
    apellidos varchar(255) NOT NULL,
    correo_personal varchar(255) NOT NULL UNIQUE,
    correo_institucional varchar(255) NOT NULL UNIQUE,
    telefono varchar(255),
    fecha_nacimiento date,
    genero char(1),
    direccion text,
    rol varchar(255) NOT NULL,
    estado boolean
);

CREATE TABLE public.facultades (
    id_facultad integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_facultad varchar(255),
    codigo_facultad varchar(255),
    ubicacion_oficina varchar(255),
    telefono_oficina varchar(255),
    email_facultad varchar(255),
    fecha_creacion date,
    estado boolean
);

CREATE TABLE public.periodos (
    id_periodo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_periodo varchar(255) NOT NULL UNIQUE,
    nombre_periodo varchar(255),
    fecha_inicio date NOT NULL,
    fecha_fin date NOT NULL,
    fecha_inicio_matriculas date,
    fecha_fin_matriculas date,
    estado_activo boolean,
    es_periodo_actual boolean
);

CREATE TABLE public.carreras (
    id_carrera integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_carrera varchar(255) NOT NULL,
    codigo_carrera varchar(255) UNIQUE,
    id_facultad integer REFERENCES public.facultades(id_facultad),
    duracion_semestres integer,
    modalidad varchar(255),
    titulo_otorga varchar(255),
    estado boolean
);

CREATE TABLE public.info_estudiantes (
    id_estudiante integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario integer NOT NULL UNIQUE REFERENCES public.usuarios(id_usuario),
    id_carrera integer REFERENCES public.carreras(id_carrera),
    id_periodo_actual integer REFERENCES public.periodos(id_periodo),
    numero_matricula varchar(255) UNIQUE,
    paralelo char(1),
    jornada varchar(255),
    fecha_ingreso timestamp(6) without time zone,
    fecha_egreso date,
    estado_academico varchar(255),
    promedio_general numeric(4,2),
    creditos_aprobados integer,
    creditos_totales integer,
    matriculado boolean,
    es_becado boolean,
    tipo_beca varchar(255),
    observaciones text
);

CREATE TABLE public.info_coordinadores (
    id_coordinador integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario integer NOT NULL UNIQUE REFERENCES public.usuarios(id_usuario),
    id_carrera integer REFERENCES public.carreras(id_carrera),
    oficina_atencion varchar(255),
    horario_atencion varchar(255),
    extension_telefonica varchar(255),
    fecha_nombramiento date,
    fecha_fin_periodo date,
    estado boolean,
    observaciones text
);

CREATE TABLE public.info_decanos (
    id_decano integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario integer NOT NULL UNIQUE REFERENCES public.usuarios(id_usuario),
    id_facultad integer REFERENCES public.facultades(id_facultad),
    fecha_nombramiento timestamp(6) without time zone,
    fecha_fin_periodo date,
    resolucion_nombramiento varchar(255),
    estado boolean,
    observaciones text
);

CREATE TABLE public.historial_matriculas (
    id_historial integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante integer NOT NULL REFERENCES public.info_estudiantes(id_estudiante),
    id_periodo integer NOT NULL REFERENCES public.periodos(id_periodo),
    id_carrera integer REFERENCES public.carreras(id_carrera),
    numero_semestre integer,
    paralelo varchar(255),
    fecha_matricula timestamp(6) without time zone,
    tipo_matricula varchar(255),
    estado_matricula varchar(255),
    observaciones text,
    CONSTRAINT uq_historial_matriculas_estudiante_periodo
        UNIQUE (id_estudiante, id_periodo)
);

COMMIT;
